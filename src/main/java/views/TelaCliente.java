    private void btnCadastrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCadastrarActionPerformed
    Cliente c = new Cliente();
    
    // 1. Pega o texto formatado (ex: "123.456.789-00")
    String cpfFormatado = txtCPF.getText();
    
    // 2. Remove a formatação para salvar no BD (ex: "12345678900")
    String cpfSemMascara = cpfFormatado.replace(".", "").replace("-", "").trim(); 
    
    c.setNome(txtNome.getText());
    // Usa o CPF limpo
    c.setCpf(cpfSemMascara); 
    c.setEmail(txtEmail.getText());
    
    ClienteDAO dao = new ClienteDAO();
    dao.create(c);
    
    limpar();
    preencherTabela();
    }//GEN-LAST:event_btnCadastrarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
    if (meuCliente != null) {
        if (JOptionPane.showConfirmDialog(null, "Tem certeza que deseja excluir este Cliente?") == JOptionPane.YES_OPTION) {
            ClienteDAO dao = new ClienteDAO();
            dao.destroy(meuCliente);
            
            limpar();
            preencherTabela();
        }
    }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void tblClientesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblClientesMouseClicked
    int linhaSelecionada = tblClientes.getSelectedRow();
    
    if (linhaSelecionada != -1) {
        // Pega o ID da primeira coluna (coluna 0)
        int id = (int) tblClientes.getValueAt(linhaSelecionada, 0);
        
        // Cria um novo objeto Cliente com os dados selecionados
        meuCliente = new Cliente();
        meuCliente.setId(id);
        meuCliente.setNome(tblClientes.getValueAt(linhaSelecionada, 1).toString());
        meuCliente.setCpf(tblClientes.getValueAt(linhaSelecionada, 2).toString());
        meuCliente.setEmail(tblClientes.getValueAt(linhaSelecionada, 3).toString());

        // Preenche os campos para edição
        txtNome.setText(meuCliente.getNome());
        txtCPF.setText(meuCliente.getCpf());
        txtEmail.setText(meuCliente.getEmail());
    }
    }//GEN-LAST:event_tblClientesMouseClicked

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
    if (meuCliente != null) {
        String cpfFormatado = txtCPF.getText();
        String cpfSemMascara = cpfFormatado.replace(".", "").replace("-", "").trim(); 
        
        // Atualiza o objeto meuCliente com os novos dados
        meuCliente.setNome(txtNome.getText());
        meuCliente.setCpf(cpfSemMascara); // <-- CPF limpo
        meuCliente.setEmail(txtEmail.getText());
        
        ClienteDAO dao = new ClienteDAO();
        dao.update(meuCliente);
        
        limpar();
        preencherTabela();
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnLimparActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLimparActionPerformed
        limpar();
    }//GEN-LAST:event_btnLimparActionPerformed

    public void limpar() {
    txtNome.setText("");
    txtCPF.setText("");
    txtEmail.setText("");
    meuCliente = null; // Zera o objeto de edição
}
    public void aplicarMascaraCPF() {
    try {
        // Define o formato: # para número, . e - são caracteres fixos
        MaskFormatter mask = new MaskFormatter("###.###.###-##");
        
        // Garante que o usuário tem que preencher todos os campos
        mask.setPlaceholderCharacter(' '); 
        
        // Instala a máscara no seu campo txtCPF
        mask.install(txtCPF);
        
    } catch (ParseException ex) {
        JOptionPane.showMessageDialog(null, "Erro ao aplicar máscara de CPF. Contate o suporte.");
        // Opcional: ex.printStackTrace(); para ver o erro no console
    }
    }
    
