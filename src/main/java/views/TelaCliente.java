public void preencherTabela() {
    DefaultTableModel dtm = (DefaultTableModel) tblClientes.getModel();
    dtm.setRowCount(0); // Limpa as linhas atuais
    
    ClienteDAO dao = new ClienteDAO();
    
    for(Cliente c : dao.read()) {
        dtm.addRow(new Object[] {
            c.getId(),
            c.getNome(),
            c.getCpf(),
            c.getEmail()
        });
    }
}
